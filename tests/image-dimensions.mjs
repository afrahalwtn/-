import assert from 'node:assert/strict';
import {imageSize,validProductImageDimensions} from '../image-guard.ts';
const png=Buffer.alloc(33);
Buffer.from([137,80,78,71,13,10,26,10]).copy(png,0);
png.writeUInt32BE(13,8);
png.write('IHDR',12,'ascii');
png.writeUInt32BE(800,16);png.writeUInt32BE(600,20);
assert.deepEqual(imageSize(png,'image/png'),{width:800,height:600});
assert(validProductImageDimensions(png,'image/png'));
const maliciousPng=Buffer.from(png);
maliciousPng.writeUInt32BE(100000,16);
maliciousPng.writeUInt32BE(100000,20);
assert.equal(validProductImageDimensions(maliciousPng,'image/png'),false,'Compressed size cannot hide huge pixel area');
assert.equal(validProductImageDimensions(Buffer.alloc(24),'image/png'),false);
const webp=Buffer.alloc(30);
webp.write('RIFF',0,'ascii');webp.write('WEBP',8,'ascii');
webp.write('VP8X',12,'ascii');webp.writeUIntLE(639,24,3);webp.writeUIntLE(479,27,3);
assert.deepEqual(imageSize(webp,'image/webp'),{width:640,height:480});
assert(validProductImageDimensions(webp,'image/webp'));
webp.writeUIntLE(65535,24,3);
assert.equal(validProductImageDimensions(webp,'image/webp'),false);
const jpeg=Buffer.from([255,216,255,224,0,4,0,0,255,192,0,7,8,0,100,0,200,255,217]);
assert.deepEqual(imageSize(jpeg,'image/jpeg'),{width:200,height:100});
assert(validProductImageDimensions(jpeg,'image/jpeg'));
assert.equal(validProductImageDimensions(Buffer.from([255,216,255,217]),'image/jpeg'),false);
console.log('PASS: JPEG, PNG, WebP dimensions and compressed pixel-bomb rejection');
